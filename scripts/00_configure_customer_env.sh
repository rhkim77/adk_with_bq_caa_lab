#!/usr/bin/env bash
# ==============================================================================
# [Step 0] Interactive Customer GCP Environment Configuration Wizard
# Generates:
#   1. customer_config.env (Root environment variables)
#   2. terraform/terraform.tfvars (Terraform input variables)
#   3. <agent_dir>/.env (Keyless Vertex AI ADC & Dataset config for all 5 ADK agents)
#
# Usage:
#   Interactive mode : ./scripts/00_configure_customer_env.sh
#   Non-interactive  : ./scripts/00_configure_customer_env.sh <PROJECT_ID> [DATASET_ID] [BQ_LOCATION] [GCP_REGION]
# ==============================================================================
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

DEFAULT_PROJECT="${GOOGLE_CLOUD_PROJECT:-}"
if [ -z "$DEFAULT_PROJECT" ] && command -v gcloud &> /dev/null; then
  DEFAULT_PROJECT="$(gcloud config get-value project 2>/dev/null || true)"
fi
DEFAULT_DATASET="${BQ_DATASET_ID:-thelook_ecommerce_agent}"
DEFAULT_BQ_LOCATION="${BQ_LOCATION:-US}"
DEFAULT_REGION="${GOOGLE_CLOUD_LOCATION:-us-central1}"

if [ $# -ge 1 ]; then
  INPUT_PROJECT="$1"
  INPUT_DATASET="${2:-$DEFAULT_DATASET}"
  INPUT_BQ_LOCATION="${3:-$DEFAULT_BQ_LOCATION}"
  INPUT_REGION="${4:-$DEFAULT_REGION}"
else
  echo "======================================================================"
  echo " 🛠️  BigQuery CAA + Google ADK Multi-Agent Lab — Customer Setup Wizard"
  echo "======================================================================"
  read -r -p "1. Enter your GCP Project ID [${DEFAULT_PROJECT}]: " INPUT_PROJECT
  INPUT_PROJECT="${INPUT_PROJECT:-$DEFAULT_PROJECT}"
  if [ -z "$INPUT_PROJECT" ]; then
    echo "❌ Error: GCP Project ID is required."
    exit 1
  fi

  read -r -p "2. Enter Target BigQuery Dataset Name [${DEFAULT_DATASET}]: " INPUT_DATASET
  INPUT_DATASET="${INPUT_DATASET:-$DEFAULT_DATASET}"

  read -r -p "3. Enter BigQuery Dataset Location (Recommended: US for 15s CTAS clone) [${DEFAULT_BQ_LOCATION}]: " INPUT_BQ_LOCATION
  INPUT_BQ_LOCATION="${INPUT_BQ_LOCATION:-$DEFAULT_BQ_LOCATION}"

  read -r -p "4. Enter Vertex AI Region for ADK Agents [${DEFAULT_REGION}]: " INPUT_REGION
  INPUT_REGION="${INPUT_REGION:-$DEFAULT_REGION}"
fi

CA_BUNDLE="$REPO_ROOT/.certs/combined_ca_bundle.pem"

# 1. Write customer_config.env
cat <<EOF > "$REPO_ROOT/customer_config.env"
# Auto-generated by scripts/00_configure_customer_env.sh
export GOOGLE_GENAI_USE_VERTEXAI="TRUE"
export GOOGLE_GENAI_USE_ENTERPRISE="TRUE"
export GOOGLE_CLOUD_PROJECT="${INPUT_PROJECT}"
export GOOGLE_CLOUD_LOCATION="${INPUT_REGION}"
export BQ_DATASET_ID="${INPUT_DATASET}"
export BQ_LOCATION="${INPUT_BQ_LOCATION}"
export GOOGLE_API_USE_CLIENT_CERTIFICATE="false"
export GOOGLE_API_USE_MTLS_ENDPOINT="never"
EOF

# 2. Write terraform/terraform.tfvars
cat <<EOF > "$REPO_ROOT/terraform/terraform.tfvars"
# Auto-generated by scripts/00_configure_customer_env.sh
project_id           = "${INPUT_PROJECT}"
region               = "${INPUT_REGION}"
dataset_id           = "${INPUT_DATASET}"
bq_location          = "${INPUT_BQ_LOCATION}"
seed_demo_data       = true
provision_caa_agents = true
EOF

# 3. Write .env for all ADK agent packages
for AGENT_DIR in "bq_caa_3domain_multi_agent" "bq_caa_toolset_agent" "bq_caa_streaming_agent" "sample_agent" "multi_agent_demo"; do
  if [ -d "$REPO_ROOT/$AGENT_DIR" ]; then
    cat <<EOF > "$REPO_ROOT/$AGENT_DIR/.env"
# Keyless Vertex AI ADC Mode (No GOOGLE_API_KEY required)
GOOGLE_GENAI_USE_VERTEXAI=TRUE
GOOGLE_GENAI_USE_ENTERPRISE=TRUE
GOOGLE_CLOUD_PROJECT=${INPUT_PROJECT}
GOOGLE_CLOUD_LOCATION=${INPUT_REGION}
BQ_DATASET_ID=${INPUT_DATASET}
BQ_LOCATION=${INPUT_BQ_LOCATION}
GOOGLE_API_USE_CLIENT_CERTIFICATE=false
GOOGLE_API_USE_MTLS_ENDPOINT=never
EOF
    if [ -f "$CA_BUNDLE" ]; then
      cat <<EOF >> "$REPO_ROOT/$AGENT_DIR/.env"
SSL_CERT_FILE=${CA_BUNDLE}
REQUESTS_CA_BUNDLE=${CA_BUNDLE}
EOF
    fi
  fi
done

echo ""
echo "✅ Customer Environment Configuration Complete!"
echo "   - GCP Project ID       : ${INPUT_PROJECT}"
echo "   - BigQuery Dataset     : ${INPUT_PROJECT}.${INPUT_DATASET} (Location: ${INPUT_BQ_LOCATION})"
echo "   - Vertex AI Region     : ${INPUT_REGION}"
echo "   - Generated Files      : customer_config.env, terraform/terraform.tfvars, <agent>/.env"
echo ""
echo "👉 Next Step (Option A - Terraform): cd terraform && terraform init && terraform apply"
echo "👉 Next Step (Option B - Script)   : source customer_config.env && python3 scripts/01_prepare_bigquery_data.py && python3 provision_bq_caa_demo.py"
